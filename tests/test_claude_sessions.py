def test_find_sessions_ranks_by_topic_and_project():
    S = [mk("a", "Login bug", age=86400 * 2), mk("b", "Dark mode", age=60),
         mk("c", "", first="login page is broken", project="/p/Site", age=100)]
    now = 1_800_000_000.0
    r = cs.find_sessions("login bug", sessions=S, now=now)
    assert [x.session.id for x in r] == ["a", "c"]
    assert not cs.is_ambiguous(r)
    r = cs.find_sessions("login", project=None, sessions=S, now=now)
    assert r[0].session.id == "a"
    assert cs.find_sessions("quantum", sessions=S, now=now) == []


def test_find_sessions_project_filter_and_empty_query_is_recency(home):
    jarvis, site, other = build_projects(home)
    r = cs.find_sessions("", sessions=cs.scan_sessions())
    assert [x.session.id for x in r] == ["v1", "j1"]
    r = cs.find_sessions("", project="jarvis", sessions=cs.scan_sessions())
    assert [x.session.id for x in r] == ["j1"]
    assert cs.find_sessions("", project="no such project", sessions=cs.scan_sessions()) == []


def test_ambiguity_when_scores_close():
    now = 1_800_000_000.0
    S = [mk("a", "Login bug", age=3600), mk("b", "Login bug fix", age=7200), mk("c", "Unrelated", age=10)]
    r = cs.find_sessions("login bug", sessions=S, now=now)
    assert [x.session.id for x in r][:2] == ["a", "b"]
    assert cs.is_ambiguous(r)
    assert not cs.is_ambiguous([])
    assert not cs.is_ambiguous([Ranked(S[0], 1.0)])
    assert not cs.is_ambiguous([Ranked(S[0], 1.0), Ranked(S[1], 0.5)])


def test_looks_busy():
    now = 1_800_000_000.0
    assert cs.looks_busy(mk("a", "x", age=5, last_kind="tool_use"), now)
    assert not cs.looks_busy(mk("a", "x", age=5, last_kind="assistant_text"), now)
    assert not cs.looks_busy(mk("a", "x", age=60, last_kind="tool_use"), now)


def test_turn_seconds(home):
    p = proj(home, "t")
    f = make(home, p, "t1", [U("go", cwd=str(p), ts="2026-10-01T10:00:00Z"), A([T("done")])])
    base = cs.parse_session(f).last_user_ts
    assert cs.turn_seconds(str(f), now=base + 90) == pytest.approx(90)
    g = make(home, p, "t2", [U("go", cwd=str(p)), A([T("done")])])
    assert cs.turn_seconds(str(g)) is None
    assert cs.turn_seconds("") is None
