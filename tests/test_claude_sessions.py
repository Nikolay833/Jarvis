def mk(id, title, first="", project="/p/Jarvis", age=3600, **kw):
    now = 1_800_000_000.0
    return Session(id=id, path="", project_dir=project, project_name=cs.basename(project), title=title,
                   first_message=first, last_activity=now - age, **kw)


def test_spoken_list_formatting():
    now = 1_800_000_000.0
    s = [mk("1", "Login bug", age=7300), mk("2", "", first="add dark mode to the settings page " * 5, project="/p/Site", age=86400)]
    out = cs.format_list(s, now)
    lines = out.splitlines()
    assert lines[0] == "1. Login bug, Jarvis, 2 hours ago"
    assert lines[1].startswith("2. add dark mode to the settings page") and lines[1].endswith(", Site, yesterday")
    assert "..." in lines[1]


def test_first_sentences_and_speakable():
    t = "**Done.** I fixed `auth.py`. Then I ran tests. They pass.\n```py\ncode\n```"
    assert cs.first_sentences(t, 2) == "Done. I fixed auth.py."
    assert cs.first_sentences("one two three four five six", 1, 3) == "one two three..."
    assert cs.first_sentences("") == ""


# ---- projects --------------------------------------------------------------------------------------------------
def build_projects(home):
    jarvis = proj(home, "Documents", "Ai on pc", "Jarvis")
    site = proj(home, "Desktop", "my-site")
    other = proj(home, "code", "VideoTest")
    proj(home, "Documents", "Taxes 2025")
    now = time.time()
    make(home, jarvis, "j1", [U("fix the login bug", cwd=str(jarvis)), A([T("Fixed.")])], now - 7200)
    make(home, other, "v1", [U("render the video", cwd=str(other)), A([T("ok")])], now - 100)
    return jarvis, site, other


def test_projects_from_history_and_known_folders(home):
    jarvis, site, other = build_projects(home)
    got = cs.projects()
    assert str(jarvis) in got and str(other) in got
    assert str(site) in got  # Desktop subfolder without sessions
    assert str(home / "Documents" / "Taxes 2025") in got
    assert str(home / "Documents") not in got and str(home / "Desktop") not in got
    assert len(got) == len(set(got))


@pytest.mark.parametrize("spoken", [
    "jarvis", "Jarvis", "the jarvis project", "jarvis project folder", "ai on pc", "jarvis pc assistant", "Jarvs",
])
def test_resolve_project_jarvis(home, spoken):
    jarvis, *_ = build_projects(home)
    assert cs.resolve_project(spoken) == str(jarvis)


def test_resolve_project_others(home):
    jarvis, site, other = build_projects(home)
    assert cs.resolve_project("video test") == str(other)
    assert cs.resolve_project("videotest") == str(other)
    assert cs.resolve_project("my site") == str(site)
    assert cs.resolve_project("taxes") == str(home / "Documents" / "Taxes 2025")
    assert cs.resolve_project("quantum fridge") is None
    assert cs.resolve_project("") is None
    assert cs.resolve_project("the project") is None
    assert cs.resolve_project(str(other)) == str(other)


