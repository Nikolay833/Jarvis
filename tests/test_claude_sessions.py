# ---- parsing --------------------------------------------------------------------------------------------
def test_parse_mixed_formats(home):
    p = proj(home, "code", "Jarvis")
    f = make(home, p, "s1", [
        {"type": "summary", "summary": "Old summary", "leafUuid": "x"},
        "garbage {{{",
        "",
        "[1, 2]",
        U("<command-name>/clear</command-name>", cwd=str(p)),
        U("Caveat: The messages below were generated by the user", cwd=str(p)),
        U("meta noise", isMeta=True),
        U("side chat", isSidechain=True),
        U([{"type": "text", "text": "fix the login bug please"}], cwd=str(p), ts="2026-10-01T10:00:00Z"),
        A([{"type": "thinking", "thinking": "hmm"}]),
        A([T("Looking at auth."), {"type": "tool_use", "name": "Read", "input": {}}]),
        {"type": "user", "message": {"content": [{"type": "tool_result", "content": "file data"}]}},
        A([{"type": "tool_use", "name": "Edit", "input": {}}]),
        A([T("Fixed **it**. All good.")]),
        {"type": "custom-title", "customTitle": "Login bug"},
    ])
    s = cs.parse_session(f)
    assert s.id == "s1" and s.project_dir == str(p) and s.project_name == "Jarvis"
    assert s.title == "Login bug"  # custom title beats summary
    assert s.first_message == "fix the login bug please"
    assert s.last_assistant_text.startswith("Fixed **it**")
    assert s.last_tool == "Edit"
    assert s.last_kind == "assistant_text"
    assert s.message_count == 4  # user + 3 assistant with content; meta/sidechain/noise/tool_result skipped
    assert s.last_user_ts == pytest.approx(1790848800.0, abs=1)
    assert s.last_activity == os.stat(f).st_mtime


def test_parse_title_fallbacks_and_decoded_dir(home):
    f = make(home, "C:\\Users\\Nik\\proj", "s2", [U("hello there"), A([T("hi")])])
    s = cs.parse_session(f)
    assert s.title == "" and s.label == "hello there"
    assert s.project_dir == "C:\\Users\\Nik\\proj" and s.project_name == "proj"
    assert cs.decode_project("C--Users-Nik-proj") == "C:\\Users\\Nik\\proj"
    assert cs.decode_project("-home-nik-proj") == "/home/nik/proj"
    f2 = make(home, "/x/y", "s3", [{"type": "summary", "summary": "Summary title"}, U("q", cwd="/x/y")])
    assert cs.parse_session(f2).title == "Summary title"
    f3 = make(home, "/x/z", "s4", [{"type": "ai-title", "aiTitle": "AI title"}, {"type": "summary", "summary": "S"},
                                    U("q", cwd="/x/z")])
    assert cs.parse_session(f3).title == "AI title"


def test_parse_empty_and_garbage_only_returns_none(home):
    assert cs.parse_session(make(home, "/a", "e1", ["nope", "{bad"])) is None
    assert cs.parse_session(make(home, "/a", "e2", [U("x", isMeta=True)])) is None
    assert cs.parse_session(home / "missing.jsonl") is None


def test_large_file_reads_head_and_tail_only(home):
    p = proj(home, "big")
    filler = [A([T("filler " * 200)]) for _ in range(800)]  # > 300 KB
    f = make(home, p, "big1", [U("the very first request", cwd=str(p))] + filler +
             [U("last request"), A([T("final answer here.")])])
    assert f.stat().st_size > cs.HEAD_BYTES + cs.TAIL_BYTES
    s = cs.parse_session(f)
    assert s.first_message == "the very first request"
    assert s.last_assistant_text == "final answer here."
    assert s.message_count >= 800


def test_cache_by_mtime_and_size(home, monkeypatch):
    p = proj(home, "c")
    f = make(home, p, "c1", [U("one", cwd=str(p)), A([T("a")])], mtime=1_000_000)
    calls = []
    real = cs.parse_session
    monkeypatch.setattr(cs, "parse_session", lambda *a, **k: (calls.append(1), real(*a, **k))[1])
    cs.load_session(f)
    cs.load_session(f)
    assert len(calls) == 1
    with f.open("a") as fh:
        fh.write(json.dumps(A([T("more")])) + "\n")
    cs.load_session(f)
    assert len(calls) == 2


def test_scan_sessions_newest_first(home):
    a, b = proj(home, "a"), proj(home, "b")
    now = time.time()
    make(home, a, "old", [U("old", cwd=str(a))], now - 5000)
    make(home, b, "new", [U("new", cwd=str(b))], now - 10)
    assert [s.id for s in cs.scan_sessions()] == ["new", "old"]


